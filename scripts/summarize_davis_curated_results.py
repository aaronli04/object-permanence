#!/usr/bin/env python3
"""Summarize DAVIS curated-subset pipeline results."""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from dataclasses import asdict, dataclass
from pathlib import Path

from davis_curated_common import SUMMARY_SCHEMA_VERSION


CLASS_PASS_THRESHOLD = 0.85
TRACK_PASS_THRESHOLD = 0.50


@dataclass(frozen=True)
class SummaryRow:
    scenario: str
    sequence: object
    group: object
    expected_classes: object
    video_status: object
    results_status: str
    enrichment_dir: str
    linking_dir: str
    trace_summary_dir: str
    trace_summary_images: int
    sampled_frames: int
    frames_with_detections: int
    detections_total: int
    detections_by_class: str
    tracks_total: int
    valid_tracks: int
    tracks_by_class: str
    expected_class_tracks: int
    expected_detection_share: float
    expected_track_share: float
    best_expected_track_hits: int
    best_expected_track_span: int
    best_expected_track_coverage: float
    accepted_relinks: int
    relink_dino_coverage: float
    class_eval: str
    track_eval: str
    overall_eval: str

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest-json",
        default="data/davis_curated_manifest.json",
        help="Input manifest generated by build_davis_curated_dataset.py.",
    )
    parser.add_argument(
        "--enrichment-root",
        default="experiments/results/activation_enrichment",
        help="Root directory for enrichment outputs.",
    )
    parser.add_argument(
        "--linking-root",
        default="experiments/results/linking",
        help="Root directory for linking outputs.",
    )
    parser.add_argument(
        "--summary-json",
        default="experiments/results/davis_curated_summary.json",
        help="Output JSON summary path.",
    )
    parser.add_argument(
        "--summary-csv",
        default="experiments/results/davis_curated_summary.csv",
        help="Output CSV summary path.",
    )
    return parser.parse_args()


def load_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def safe_counter_str(counter: Counter[str]) -> str:
    return ",".join(f"{key}:{counter[key]}" for key in sorted(counter))


def eval_flag(passed: bool) -> str:
    return "PASS" if passed else "FAIL"


def expected_share(counter: Counter[str], expected_classes: set[str]) -> float:
    total = sum(counter.values())
    if total <= 0:
        return 0.0
    expected_total = sum(count for label, count in counter.items() if label in expected_classes)
    return float(expected_total) / float(total)


def summarize_item(
    item: dict[str, object],
    enrichment_root: Path,
    linking_root: Path,
) -> SummaryRow:
    scenario = str(item["scenario"])
    expected_classes = {part for part in str(item["expected_classes"]).split(",") if part}
    enriched_path = enrichment_root / scenario / "enriched_detections.json"
    tracks_path = linking_root / scenario / "tracks.json"
    relink_path = linking_root / scenario / "relink_manifest.json"
    trace_summary_dir = linking_root / scenario / "trace_summary"

    row = SummaryRow(
        scenario=scenario,
        sequence=item["sequence"],
        group=item["group"],
        expected_classes=item["expected_classes"],
        video_status=item["status"],
        results_status="missing",
        enrichment_dir=str(enrichment_root / scenario),
        linking_dir=str(linking_root / scenario),
        trace_summary_dir=str(trace_summary_dir),
        trace_summary_images=0,
        sampled_frames=0,
        frames_with_detections=0,
        detections_total=0,
        detections_by_class="",
        tracks_total=0,
        valid_tracks=0,
        tracks_by_class="",
        expected_class_tracks=0,
        expected_detection_share=0.0,
        expected_track_share=0.0,
        best_expected_track_hits=0,
        best_expected_track_span=0,
        best_expected_track_coverage=0.0,
        accepted_relinks=0,
        relink_dino_coverage=0.0,
        class_eval="FAIL",
        track_eval="FAIL",
        overall_eval="FAIL",
    )

    if not (enriched_path.exists() and tracks_path.exists() and relink_path.exists()):
        return row

    frames = load_json(enriched_path)
    tracks_payload = load_json(tracks_path)
    relink_payload = load_json(relink_path)

    if not isinstance(frames, list):
        return row
    if not isinstance(tracks_payload, dict):
        return row
    if not isinstance(relink_payload, dict):
        return row

    detection_counts: Counter[str] = Counter()
    sampled_frames = len(frames)
    frames_with_detections = 0
    detections_total = 0
    for frame in frames:
        if not isinstance(frame, dict):
            continue
        detections = frame.get("detections", [])
        if not isinstance(detections, list):
            continue
        if detections:
            frames_with_detections += 1
        for det in detections:
            if not isinstance(det, dict):
                continue
            label = str(det.get("class_name") or det.get("label") or "UNKNOWN")
            detection_counts[label] += 1
            detections_total += 1

    tracks = tracks_payload.get("tracks", [])
    if not isinstance(tracks, list):
        tracks = []
    track_counts: Counter[str] = Counter()
    valid_tracks = 0
    expected_class_tracks = 0
    best_expected_track_hits = 0
    best_expected_track_span = 0
    for track in tracks:
        if not isinstance(track, dict):
            continue
        label = str(track.get("class_name") or track.get("label") or "UNKNOWN")
        track_counts[label] += 1
        if bool(track.get("valid_track")):
            valid_tracks += 1
        if label in expected_classes:
            expected_class_tracks += 1
            hits = int(track.get("hits") or 0)
            best_expected_track_hits = max(best_expected_track_hits, hits)
            start_frame = int(track.get("start_frame") or 0)
            end_frame = int(track.get("end_frame") or 0)
            best_expected_track_span = max(best_expected_track_span, max(0, end_frame - start_frame + 1))

    stats = relink_payload.get("stats", {})
    accepted_relinks = 0
    relink_dino_coverage = 0.0
    if isinstance(stats, dict):
        accepted_relinks = int(stats.get("num_accepted_edges") or 0)
        relink_dino_coverage = float(stats.get("relink_dino_coverage") or 0.0)

    trace_summary_images = len(list(trace_summary_dir.glob("*.jpg"))) if trace_summary_dir.exists() else 0
    detection_share = expected_share(detection_counts, expected_classes)
    track_share = expected_share(track_counts, expected_classes)
    best_track_coverage = (float(best_expected_track_hits) / float(sampled_frames)) if sampled_frames > 0 else 0.0
    class_eval = eval_flag(detection_share >= CLASS_PASS_THRESHOLD)
    track_eval = eval_flag(best_track_coverage >= TRACK_PASS_THRESHOLD)
    overall_eval = eval_flag(class_eval == "PASS" and track_eval == "PASS")

    return SummaryRow(
        scenario=row.scenario,
        sequence=row.sequence,
        group=row.group,
        expected_classes=row.expected_classes,
        video_status=row.video_status,
        results_status="ok",
        enrichment_dir=row.enrichment_dir,
        linking_dir=row.linking_dir,
        trace_summary_dir=row.trace_summary_dir,
        trace_summary_images=trace_summary_images,
        sampled_frames=sampled_frames,
        frames_with_detections=frames_with_detections,
        detections_total=detections_total,
        detections_by_class=safe_counter_str(detection_counts),
        tracks_total=len(tracks),
        valid_tracks=valid_tracks,
        tracks_by_class=safe_counter_str(track_counts),
        expected_class_tracks=expected_class_tracks,
        expected_detection_share=detection_share,
        expected_track_share=track_share,
        best_expected_track_hits=best_expected_track_hits,
        best_expected_track_span=best_expected_track_span,
        best_expected_track_coverage=best_track_coverage,
        accepted_relinks=accepted_relinks,
        relink_dino_coverage=relink_dino_coverage,
        class_eval=class_eval,
        track_eval=track_eval,
        overall_eval=overall_eval,
    )


def write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def write_csv(path: Path, rows: list[SummaryRow]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "scenario",
        "sequence",
        "group",
        "expected_classes",
        "video_status",
        "results_status",
        "enrichment_dir",
        "linking_dir",
        "trace_summary_dir",
        "trace_summary_images",
        "sampled_frames",
        "frames_with_detections",
        "detections_total",
        "detections_by_class",
        "tracks_total",
        "valid_tracks",
        "tracks_by_class",
        "expected_class_tracks",
        "expected_detection_share",
        "expected_track_share",
        "best_expected_track_hits",
        "best_expected_track_span",
        "best_expected_track_coverage",
        "accepted_relinks",
        "relink_dino_coverage",
        "class_eval",
        "track_eval",
        "overall_eval",
    ]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow(row.to_dict())


def main() -> int:
    args = parse_args()
    manifest = load_json(Path(args.manifest_json))
    if not isinstance(manifest, dict):
        raise SystemExit("Manifest JSON must be an object.")
    items = manifest.get("items", [])
    if not isinstance(items, list):
        raise SystemExit("Manifest JSON must contain list field 'items'.")

    enrichment_root = Path(args.enrichment_root)
    linking_root = Path(args.linking_root)
    rows: list[SummaryRow] = [
        summarize_item(item, enrichment_root, linking_root)
        for item in items
        if isinstance(item, dict)
    ]

    videos_with_results = sum(1 for row in rows if row.results_status == "ok")
    videos_with_expected_tracks = sum(1 for row in rows if int(row.expected_class_tracks) > 0)
    videos_with_valid_tracks = sum(1 for row in rows if int(row.valid_tracks) > 0)
    aggregate = {
        "schema_version": SUMMARY_SCHEMA_VERSION,
        "videos_total": len(rows),
        "videos_with_results": videos_with_results,
        "videos_with_expected_tracks": videos_with_expected_tracks,
        "videos_with_valid_tracks": videos_with_valid_tracks,
        "items": [row.to_dict() for row in rows],
    }

    write_json(Path(args.summary_json), aggregate)
    write_csv(Path(args.summary_csv), rows)

    print(f"Videos total:             {len(rows)}")
    print(f"Videos with results:      {videos_with_results}")
    print(f"Videos with expected IDs: {videos_with_expected_tracks}")
    print(f"Videos with valid tracks: {videos_with_valid_tracks}")
    print(f"Summary JSON:             {args.summary_json}")
    print(f"Summary CSV:              {args.summary_csv}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
